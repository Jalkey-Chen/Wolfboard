function interpolate(template: string, values?: TranslationValues): string {
  if (!values) {
    return template;
  }

  return Object.entries(values).reduce(
    (message, [key, value]) => message.replaceAll(`{${key}}`, String(value)),
    template,
  );
}

/** Read the preferred language from localStorage with a safe Chinese fallback. */
export function getStoredLanguage(): Language {
  if (typeof window === "undefined") {
    return DEFAULT_LANGUAGE;
  }

  const stored = window.localStorage.getItem(LANGUAGE_STORAGE_KEY);
  return stored === "en" || stored === "zh" ? stored : DEFAULT_LANGUAGE;
}

/** Persist the user's language choice for later visits. */
export function persistLanguage(language: Language): void {
  if (typeof window === "undefined") {
    return;
  }

  window.localStorage.setItem(LANGUAGE_STORAGE_KEY, language);
}

/** Map the app language to a browser locale used by date formatting helpers. */
export function getLocaleForLanguage(language: Language): string {
  return language === "zh" ? "zh-CN" : "en-US";
}

/** Resolve a translated message and interpolate any template placeholders. */
export function translate(
  language: Language,
  key: string,
  values?: TranslationValues,
): string {
  const template = translations[language][key] ?? translations.en[key] ?? key;
  return interpolate(template, values);
}

/** Translate enum-backed status and category values shown throughout the UI. */
export function translateEnum(
  language: Language,
  group: EnumGroup,
  value: string | null | undefined,
): string {
  if (!value) {
    return translate(language, "common.notSet");
  }

  return enumTranslations[group][value]?.[language]
    ?? enumTranslations[group][value]?.en
    ?? value;
}

/**
 * Resolve a localized preset-format description.
 *
 * Seed data still stores a single backend description field, so the frontend
 * maps known preset `format_key` values to bilingual copy until richer content
 * modeling is introduced later.
 */
export function translatePresetFormatDescription(
  language: Language,
  formatKey: string | null | undefined,
  fallback?: string | null,
): string {
  if (formatKey && presetFormatDescriptions[formatKey]?.[language]) {
    return presetFormatDescriptions[formatKey][language];
  }

  return fallback ?? translate(language, "formats.noDescription");
}

